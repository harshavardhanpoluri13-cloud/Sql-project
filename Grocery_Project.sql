-- 2. What is the average value per order?
select avg(total_price) as average_order_value from order_details;

SELECT AVG(order_total) AS avg_order_value
FROM (
    SELECT o.ord_id, SUM(od.total_price) AS order_total
    FROM orders o
    JOIN order_details od ON o.ord_id = od.ord_id
    GROUP BY o.ord_id
) AS order_summary;

-- 3. On which dates were the most orders placed?
SELECT order_date, COUNT(ord_id) AS number_of_orders
FROM orders
