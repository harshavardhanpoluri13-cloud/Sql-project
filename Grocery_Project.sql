-- 4. What are the monthly trends in order volume and revenue?
select
 month(str_to_date(order_date,"%m/%d/%Y")) as month,
count(distinct o.ord_id) as volume,
sum(od.quantity*od.each_price) as revenue
from orders o
join order_details od on o.ord_id= od.ord_id
group by month;


-- 5. How do order patterns vary across weekdays and weekends?
with cte1 as 
(select ord_id,dayofweek(str_to_date(order_date,"%m/%d/%Y")) as days from orders),
cte2 as 
(select *,case when days IN (1, 7) THEN 'Weekend'else 'Weekday'end as order_type from cte1)
select distinct order_type,count(ord_id) over (partition by order_type) as no_of_order from cte2;


